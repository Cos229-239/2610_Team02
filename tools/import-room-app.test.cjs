'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {prepare,install}=require('./import-room-app.cjs');
test('publication follows shared dev while a different dirty personal branch is checked out', t=>{
    const temp=fs.mkdtempSync(path.join(os.tmpdir(),'tf-publish-test-'));
    t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
    const checkout=path.join(temp,'host'),room=path.join(temp,'room');
    fs.mkdirSync(checkout);fs.mkdirSync(room);fs.writeFileSync(path.join(room,'server.js'),'');
    const git=(...args)=>execFileSync('git',args,{cwd:checkout,encoding:'utf8'}).trim();
    git('init','--quiet','-b','dev');git('config','user.name','Fixture');git('config','user.email','fixture@example.org');
    fs.mkdirSync(path.join(checkout,'TowerFlow'));fs.mkdirSync(path.join(checkout,'tools'));
    const entry=path.join(checkout,'TowerFlow/index.html');
    fs.writeFileSync(entry,'team');fs.writeFileSync(path.join(checkout,'TowerFlow/old.css'),'a{}');
    fs.writeFileSync(path.join(checkout,'tools/check-contributions.cjs'),"require('node:assert/strict').equal(require('node:fs').readFileSync('TowerFlow/index.html','utf8'),'team')");
    git('add','.');git('commit','--quiet','-m','Team app');
    const initial=git('rev-parse','HEAD'),remote=path.join(temp,'team.git');
    git('clone','--quiet','--bare',checkout,remote);
    git('switch','-q','-c','dan-personal');fs.writeFileSync(entry,'personal');git('commit','-qam','Personal app');fs.writeFileSync(entry,'local edits');
    install(room,true,{checkout,remote});
    const published=path.join(room,'public/towerflow');
    assert.equal(fs.readFileSync(path.join(published,'index.html'),'utf8'),'team');
    assert.equal(JSON.parse(fs.readFileSync(path.join(published,'towerflow-build.json'))).revision,initial);
    const team=path.join(temp,'member');git('clone','--quiet',remote,team);
    const member=(...args)=>execFileSync('git',args,{cwd:team});
    member('config','user.name','Member');member('config','user.email','member@example.org');member('rm','--quiet','TowerFlow/old.css');member('commit','-qm','Remove obsolete style');member('push','--quiet','origin','dev');
    fs.writeFileSync(path.join(published,'room-only.js'),'host');
    assert.deepEqual(prepare(room,{checkout,remote}).removals,['old.css']);
    install(room,true,{checkout,remote});
    assert.equal(fs.existsSync(path.join(published,'old.css')),false);
    assert.equal(fs.readFileSync(path.join(published,'room-only.js'),'utf8'),'host');
    assert.equal(git('branch','--show-current'),'dan-personal');assert.equal(fs.readFileSync(entry,'utf8'),'local edits');
});
